"""Feishu application bot transport. No secrets or raw responses in errors."""
import ctypes
from ctypes import wintypes
import hashlib
import json
import os
from pathlib import Path
import threading
import time
from urllib.request import Request, urlopen
from urllib.error import HTTPError

BASE = 'https://open.feishu.cn/open-apis'
DEFAULT_CREDENTIALS = Path(__file__).parent / 'runtime' / 'feishu-app.dpapi'
GROUP_CREDENTIALS = Path(__file__).parent / 'runtime' / 'feishu-group.dpapi'
EVIDENCE_CREDENTIALS = Path(__file__).parent / 'runtime' / 'feishu-evidence.dpapi'


class FeishuError(RuntimeError):
    pass


def protect(data, decrypt=False):
    """DPAPI current Windows user, with UI forbidden; never plaintext on disk."""
    if os.name != 'nt':
        raise FeishuError('Windows credential protection required')
    class Blob(ctypes.Structure):
        _fields_ = [('size', wintypes.DWORD), ('data', ctypes.POINTER(ctypes.c_ubyte))]
    buffer = ctypes.create_string_buffer(data)
    source = Blob(len(data), ctypes.cast(buffer, ctypes.POINTER(ctypes.c_ubyte)))
    output = Blob()
    crypt = ctypes.WinDLL('crypt32', use_last_error=True)
    crypt.CryptProtectData.argtypes = [ctypes.POINTER(Blob), wintypes.LPCWSTR,
        ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, wintypes.DWORD, ctypes.POINTER(Blob)]
    crypt.CryptUnprotectData.argtypes = [ctypes.POINTER(Blob), ctypes.c_void_p,
        ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, wintypes.DWORD, ctypes.POINTER(Blob)]
    kernel = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel.LocalFree.argtypes = [ctypes.c_void_p]
    kernel.LocalFree.restype = ctypes.c_void_p
    if decrypt:
        ok = crypt.CryptUnprotectData(ctypes.byref(source), None, None, None, None, 1, ctypes.byref(output))
    else:
        ok = crypt.CryptProtectData(ctypes.byref(source), 'Lab Feishu application', None, None, None, 1, ctypes.byref(output))
    if not ok:
        raise FeishuError('Windows credential protection failed')
    try:
        return ctypes.string_at(output.data, output.size)
    finally:
        kernel.LocalFree(ctypes.cast(output.data, ctypes.c_void_p))


def save_credentials(credentials, path=DEFAULT_CREDENTIALS):
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    encrypted = protect(json.dumps(credentials).encode())
    temporary = target.with_suffix('.tmp')
    temporary.write_bytes(encrypted)
    temporary.replace(target)


def load_credentials(path=DEFAULT_CREDENTIALS):
    try:
        return json.loads(protect(Path(path).read_bytes(), decrypt=True))
    except FeishuError:
        raise
    except Exception:
        raise FeishuError('application credentials unavailable') from None


def api_request(method, path, payload, token=None):
    # Paths are entirely generated by this module, not by external event data.
    headers = {'Content-Type': 'application/json; charset=utf-8'}
    if token:
        headers['Authorization'] = 'Bearer ' + token
    req = Request(BASE + path, data=json.dumps(payload, ensure_ascii=False).encode(),
                  headers=headers, method=method)
    try:
        with urlopen(req, timeout=5) as response:
            result = json.loads(response.read(1024 * 1024))
    except HTTPError as exc:
        try:
            result = json.loads(exc.read(1024 * 1024))
        except Exception:
            raise FeishuError('飞书请求失败，HTTP状态=' + str(exc.code)) from None
    except Exception:
        raise FeishuError('连接飞书失败，请检查网络和应用权限') from None
    if not isinstance(result, dict) or result.get('code') != 0:
        code = result.get('code', 'unknown') if isinstance(result, dict) else 'unknown'
        raise FeishuError('飞书拒绝请求，错误码=' + str(code))
    return result


class FeishuAppClient:
    def __init__(self, credentials, request=api_request, wall=time.time):
        self.credentials = dict(credentials)
        if not credentials.get('app_id', '').startswith('cli_') or not credentials.get('app_secret'):
            raise FeishuError('App ID and App Secret required')
        self.request, self.wall = request, wall
        self.lock = threading.RLock()
        self._token = None
        self._deadline = 0

    def token(self):
        with self.lock:
            if self._token and self.wall() < self._deadline:
                return self._token
            result = self.request('POST', '/auth/v3/tenant_access_token/internal',
                                  {k: self.credentials[k] for k in ('app_id', 'app_secret')})
            if not result.get('tenant_access_token') or result.get('expire', 0) <= 60:
                raise FeishuError('invalid application token response')
            self._token = result['tenant_access_token']
            self._deadline = self.wall() + result['expire'] - 60
            return self._token

    def resolve_recipient(self, address):
        address = address.strip()
        if address.startswith('ou_'):
            return address
        if not address:
            raise FeishuError('recipient mobile/email/open_id required')
        field = 'emails' if '@' in address else 'mobiles'
        body = self.request('POST', '/contact/v3/users/batch_get_id?user_id_type=open_id',
                            {field: [address]}, self.token())
        users = body.get('data', {}).get('user_list', [])
        identifiers = {u.get('user_id') for u in users if isinstance(u, dict) and u.get('user_id')}
        if not identifiers:
            raise FeishuError('飞书查询成功，但未返回此接收人的编号。请确认：接收人属于该应用所在组织；'
                              '手机号或邮箱与组织通讯录一致；通讯录权限范围包含接收人；修改已发布生效。')
        if len(identifiers) != 1:
            raise FeishuError('接收人查询存在歧义，未发送消息。请使用此应用下明确的 open_id。')
        if not next(iter(identifiers)).startswith('ou_'):
            raise FeishuError('接收人编号类型不是 open_id，未发送消息。请检查接口编号类型。')
        return next(iter(identifiers))

    def send_text(self, open_id, text, event_id):
        if not isinstance(open_id, str) or not open_id.startswith('ou_'):
            raise FeishuError('validated recipient open_id required')
        # Stable per-recipient UUID supports Feishu message request deduplication.
        request_id = hashlib.sha256((event_id + '|' + open_id).encode()).hexdigest()[:32]
        body = self.request('POST', '/im/v1/messages?receive_id_type=open_id',
            {'receive_id': open_id, 'msg_type': 'text',
             'content': json.dumps({'text': text}, ensure_ascii=False), 'uuid': request_id}, self.token())
        message_id = body.get('data', {}).get('message_id')
        if not message_id:
            raise FeishuError('message acknowledgement missing')
        return message_id

    def upload_image(self, jpeg):
        if not isinstance(jpeg, bytes) or not jpeg.startswith(b'\xff\xd8') or len(jpeg) > 10 * 1024 * 1024:
            raise FeishuError('证据图片必须是10MB以内的JPEG')
        import secrets
        boundary = 'LabEvidence' + secrets.token_hex(16)
        data = (('--'+boundary+'\r\nContent-Disposition: form-data; name="image_type"\r\n\r\nmessage\r\n'
                 '--'+boundary+'\r\nContent-Disposition: form-data; name="image"; filename="evidence.jpg"\r\n'
                 'Content-Type: image/jpeg\r\n\r\n').encode() + jpeg + ('\r\n--'+boundary+'--\r\n').encode())
        req = Request(BASE+'/im/v1/images', data=data, method='POST', headers={
            'Authorization':'Bearer '+self.token(), 'Content-Type':'multipart/form-data; boundary='+boundary})
        try:
            with urlopen(req,timeout=8) as response:
                result=json.loads(response.read(65536))
        except HTTPError as exc:
            try: result=json.loads(exc.read(65536))
            except Exception: raise FeishuError('图片上传失败，HTTP='+str(exc.code)) from None
        except Exception:
            raise FeishuError('图片上传网络失败') from None
        if result.get('code') != 0 or not result.get('data',{}).get('image_key'):
            code=result.get('code')
            raise FeishuError('图片上传被拒绝，请检查im:resource权限及应用发布状态。错误码='+
                              (str(code) if isinstance(code,int) else 'unknown'))
        return result['data']['image_key']

    def urgent_phone(self, message_id, open_id, enabled=False):
        if not enabled:
            raise FeishuError('phone escalation disabled')
        if (not message_id.startswith('om_') or not open_id.startswith('ou_')
                or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_' for c in message_id)):
            raise FeishuError('invalid escalation identifiers')
        result = self.request('PATCH', '/im/v1/messages/' + message_id + '/urgent_phone?user_id_type=open_id',
                              {'user_id_list': [open_id]}, self.token())
        if result.get('data', {}).get('invalid_user_id_list'):
            raise FeishuError('phone recipient rejected')
        return result
